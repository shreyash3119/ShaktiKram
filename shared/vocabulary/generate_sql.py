#!/usr/bin/env python3
"""Generate the Stage 1 vocabulary migrations (reference seeds and CHECK constraints) from the JSON files.
This writes the Stage 1 snapshot once. Later vocabulary changes need a NEW hand-written migration;
backend/tests/check_vocabulary_sync.py fails the build if the database and the JSON disagree."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
MIG = HERE.parents[1] / "backend" / "supabase" / "migrations"
load = lambda n: json.load(open(HERE / n, encoding="utf-8"))
q = lambda s: "'" + s.replace("'", "''") + "'"

# (table, column, list name in statuses.json). Extend when a later stage adds tables.
CHECKS = [
    ("pfs_registry", "record_class", "record_class"),
    ("goals", "type", "goal_type"), ("goals", "status", "goal_status"),
    ("goal_status_events", "status", "goal_status"),
    ("reminder_rules", "kind", "reminder_kind"),
    ("devices", "platform", "device_platform"),
    ("sync_operations", "action", "sync_operation_action"), ("sync_operations", "result", "sync_operation_result"),
    ("audit_log", "action", "audit_action"),
    ("settings", "weight_unit", "display_weight_unit"), ("settings", "length_unit", "display_length_unit"),
    ("settings", "distance_unit", "display_distance_unit"), ("settings", "week_start", "calendar_week_start_options"),
    ("profile_versions", "experience_level", "experience_level"),
]
CHECKS_2 = [
    ("exercises", "category", "exercise_category"),
    ("exercise_muscles", "role", "muscle_role"),
    ("splits", "status", "split_status"), ("split_status_events", "status", "split_status"),
    ("split_versions", "pattern", "split_pattern"),
    ("schedule_entries", "status", "schedule_entry_status"),
    ("gym_decisions", "outcome", "gym_decision_outcome"),
    ("planned_breaks", "mode", "break_mode"), ("planned_breaks", "status", "break_status"), ("planned_breaks", "reason", "break_reason"),
    ("break_events", "event", "break_event"),
    ("workout_sessions", "status", "session_status"),
    ("session_exercises", "status", "session_exercise_status"),
    ("sets", "set_type", "set_type"),
]

CHECKS_3 = [
    ("body_measurements", "measurement_type", "body_measurement_type"), ("body_measurements", "method", "body_fat_method"),
    ("body_measurements", "source", "data_source"), ("body_measurements", "side", "body_side"),
    ("injuries", "side", "body_side"), ("injuries", "status", "injury_status"), ("injuries", "severity", "injury_severity"),
    ("injury_updates", "status", "injury_status"), ("injury_updates", "severity", "injury_severity"),
    ("pain_entries", "side", "body_side"), ("pain_entries", "effect_on_training", "pain_effect_on_training"),
    ("exercise_restrictions", "kind", "restriction_kind"), ("exercise_restrictions", "source", "restriction_source"),
    ("supplement_phases", "status", "supplement_phase_status"), ("supplement_logs", "outcome", "supplement_outcome"),
    ("meals", "category", "meal_category"), ("meal_plan_entries", "slot", "meal_category"), ("meal_plan_entries", "status", "meal_plan_status"),
    ("cardio_sessions", "activity", "cardio_activity"), ("cardio_sessions", "intensity", "cardio_intensity"),
    ("cardio_sessions", "source", "data_source"), ("daily_steps", "source", "data_source"),
    ("weak_point_events", "event", "weak_point_event"),
]


def main():
    st = load("statuses.json")
    lines = ["-- GENERATED by shared/vocabulary/generate_sql.py from shared/vocabulary/statuses.json. Do not edit.", ""]
    for t, c, l in CHECKS:
        vals = ", ".join(q(v) for v in st[l])
        lines.append(f"alter table {t} add constraint ck_{t}_{c}_values check ({c} in ({vals}));")
    lines2 = ["-- GENERATED by shared/vocabulary/generate_sql.py from shared/vocabulary/statuses.json. Do not edit.", ""]
    for t, c, l in CHECKS_2:
        vals = ", ".join(q(v) for v in st[l])
        lines2.append(f"alter table {t} add constraint ck_{t}_{c}_values check ({c} in ({vals}));")
    (MIG / "20261107000600_stage2_vocabulary_checks.sql").write_text("\n".join(lines2) + "\n")
    lines3 = ["-- GENERATED by shared/vocabulary/generate_sql.py from shared/vocabulary/statuses.json. Do not edit.", ""]
    for t, c, l in CHECKS_3:
        vals = ", ".join(q(v) for v in st[l])
        lines3.append(f"alter table {t} add constraint ck_{t}_{c}_values check ({c} in ({vals}));")
    (MIG / "20261108000600_stage3_vocabulary_checks.sql").write_text("\n".join(lines3) + "\n")
    (MIG / "20261106000600_vocabulary_checks.sql").write_text("\n".join(lines) + "\n")

    def seed(table, rows, cols):
        out = [f"insert into {table} (id, {', '.join(cols)}, is_custom) values"]
        out.append(",\n".join(f"  (md5({q(table + ':' + r[0])})::uuid, " + ", ".join(q(x) for x in r) + ", false)" for r in rows))
        out.append("on conflict (key) do nothing;")
        return "\n".join(out)

    m, b, e = load("muscles.json"), load("body_regions.json"), load("equipment.json")
    body = ["-- GENERATED by shared/vocabulary/generate_sql.py from the vocabulary JSON files. Do not edit.",
            "-- Seeded rows get deterministic ids (md5 of table:key) so every environment agrees.", "",
            seed("muscles", [(x["key"], x["group"], x["label"]) for x in m["muscles"]], ["key", "group_key", "label"]), "",
            seed("body_regions", [(x["key"], x["label"]) for x in b["body_regions"]], ["key", "label"]), "",
            seed("equipment", [(x["key"], x["label"]) for x in e["equipment"]], ["key", "label"])]
    (MIG / "20261106000700_seed_reference.sql").write_text("\n".join(body) + "\n")
    print("generated vocabulary migrations")


if __name__ == "__main__":
    main()
