-- Stage 1 / access: one owner account (Supabase Auth), devices, owner claim, device revocation.
-- Decision D3: sign-ups are disabled; the owner signs in once per device and the session persists.

create table devices (
  id uuid primary key,                          -- generated by the device
  label text not null,
  platform text not null,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz,
  last_pull_rev bigint not null default 0,
  revoked_at timestamptz
);
select pfs_secure('devices');

create function pfs_require_owner() returns void language plpgsql stable security definer set search_path = public, pg_temp as $$
begin
  if auth.uid() is null or not is_owner() then raise exception 'unauthorized: owner sign-in required' using errcode = 'PT401'; end if;
end $$;

-- Checks the owner and the device, then stamps the transaction with the device id (used by triggers and audit).
create function pfs_require_device(p_device_id uuid) returns void language plpgsql security definer set search_path = public, pg_temp as $$
declare d devices%rowtype;
begin
  perform pfs_require_owner();
  select * into d from devices where id = p_device_id;
  if not found then raise exception 'unauthorized: device is not registered' using errcode = 'PT401'; end if;
  if d.revoked_at is not null then raise exception 'device_revoked: this device was revoked' using errcode = 'PT403'; end if;
  update devices set last_seen_at = now() where id = p_device_id;
  perform set_config('pfs.device_id', p_device_id::text, true);
  perform set_config('pfs.restore_mode', 'off', true);
  perform set_config('pfs.allow_purge', 'off', true);
end $$;

-- The first signed-in user to call this becomes the owner. After that, nobody else can.
create function api_claim_owner() returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
begin
  if auth.uid() is null then raise exception 'unauthorized: sign in first' using errcode = 'PT401'; end if;
  insert into app_owner (auth_user_id) values (auth.uid()) on conflict do nothing;
  if not is_owner() then raise exception 'unauthorized: this app already has an owner' using errcode = 'PT401'; end if;
  return jsonb_build_object('data', jsonb_build_object('owner', true), 'meta', pfs_meta());
end $$;

create function api_register_device(p_device_id uuid, p_label text, p_platform text) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare d devices%rowtype;
begin
  perform pfs_require_owner();
  select * into d from devices where id = p_device_id;
  if found and d.revoked_at is not null then raise exception 'device_revoked: this device was revoked' using errcode = 'PT403'; end if;
  insert into devices (id, label, platform, last_seen_at) values (p_device_id, p_label, p_platform, now())
  on conflict (id) do update set label = excluded.label, last_seen_at = now();
  select * into d from devices where id = p_device_id;
  return jsonb_build_object('data', to_jsonb(d), 'meta', pfs_meta());
end $$;

create function api_list_devices() returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
begin
  perform pfs_require_owner();
  return jsonb_build_object('data', coalesce((select jsonb_agg(to_jsonb(d) order by d.created_at) from devices d), '[]'::jsonb), 'meta', pfs_meta());
end $$;

-- Revoking blocks the device's writes and pulls at once. Also sign the device's session out in Supabase Auth (see backend/README.md).
create function api_revoke_device(p_device_id uuid) returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare d devices%rowtype;
begin
  perform pfs_require_owner();
  update devices set revoked_at = coalesce(revoked_at, now()) where id = p_device_id returning * into d;
  if not found then raise exception 'not_found: device not found' using errcode = 'PT404'; end if;
  return jsonb_build_object('data', to_jsonb(d), 'meta', pfs_meta());
end $$;
